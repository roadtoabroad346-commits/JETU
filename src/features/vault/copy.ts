export function vaultCopy(locale: Locale): VaultCopy {
  const index = locale === 'ru' ? 1 : locale === 'kk' ? 2 : 0;
  return Object.fromEntries(
    Object.entries(vocabulary).map(([key, values]) => [key, values[index]]),
  ) as VaultCopy;
}
